import { getItem, setItem } from '../utils/storage.js';

const SUBJECT_LABELS = {
  russian: 'Русский язык',
  literature: 'Литература',
  pedagogy: 'Педагогика',
};

const TYPE_LABELS = {
  course: 'Курсовая работа',
  project: 'Проектная работа',
  research: 'Исследовательская работа',
};

function chapterOutline(topic, subject) {
  if (subject === 'literature') {
    return [
      `Глава 1. Теоретические основы изучения темы «${topic}»`,
      '  1.1. Литературоведческий анализ проблемы',
      '  1.2. Методы исследования художественного текста',
      `Глава 2. Анализ произведения в контексте темы «${topic}»`,
      '  2.1. Художественные особенности и композиция',
      '  2.2. Образная система и авторская позиция',
      'Глава 3. Практическое исследование и выводы',
      '  3.1. Сопоставительный анализ материала',
      '  3.2. Результаты исследования',
    ];
  }
  if (subject === 'pedagogy') {
    return [
      `Глава 1. Теоретико-методологические основы темы «${topic}»`,
      '  1.1. Педагогические подходы и понятийный аппарат',
      '  1.2. Современное состояние проблемы',
      `Глава 2. Методика и организация исследования`,
      '  2.1. Этапы и методы педагогического исследования',
      '  2.2. Диагностические и формирующие процедуры',
      'Глава 3. Результаты и практические рекомендации',
      '  3.1. Анализ полученных данных',
      '  3.2. Рекомендации для педагогической практики',
    ];
  }
  return [
    `Глава 1. Теоретические основы темы «${topic}»`,
    '  1.1. Понятие, сущность и виды явления',
    '  1.2. Нормативно-правовая и научная база',
    `Глава 2. Анализ языкового материала по теме «${topic}»`,
    '  2.1. Методы лингвистического анализа',
    '  2.2. Примеры и интерпретация результатов',
    'Глава 3. Практическое применение и выводы',
    '  3.1. Рекомендации для обучения',
    '  3.2. Итоги исследования',
  ];
}

function buildTasks(topic) {
  return [
    `раскрыть теоретические основы темы «${topic}»;`,
    'проанализировать научную и методическую литературу по проблеме;',
    'выявить особенности и закономерности исследуемого явления;',
    'сформулировать практические рекомендации и выводы.',
  ];
}

function objectSubject(subject) {
  if (subject === 'literature') {
    return {
      object: 'процесс изучения и интерпретации художественной литературы в образовательной среде',
      subject: 'литературные произведения, образы и смысловые связи в рамках выбранной темы',
    };
  }
  if (subject === 'pedagogy') {
    return {
      object: 'процесс обучения и воспитания в образовательной организации',
      subject: 'педагогические условия, методы и результаты, связанные с выбранной темой',
    };
  }
  return {
    object: 'процесс обучения русскому языку',
    subject: 'языковые явления, правила и способы их усвоения в рамках выбранной темы',
  };
}

export function generateStructure(topic, subject, type, requirements = '') {
  const subjectLabel = SUBJECT_LABELS[subject] || subject;
  const typeLabel = TYPE_LABELS[type] || type;
  const { object, subject: researchSubject } = objectSubject(subject);
  const tasks = buildTasks(topic);
  const chapters = chapterOutline(topic, subject);

  const contents = [
    'Введение',
    'Глава 1. Теоретическая часть',
    'Глава 2. Аналитическая часть',
    'Глава 3. Практическая часть',
    'Заключение',
    'Список литературы',
    'Приложения (при необходимости)',
  ];

  const sections = [
    {
      id: 'header',
      title: 'Титульный лист',
      content: [
        'Министерство образования',
        '[Название учебного заведения]',
        '',
        typeLabel.toUpperCase(),
        `на тему: «${topic}»`,
        '',
        `Предмет: ${subjectLabel}`,
        '',
        'Выполнил(а): ___________________________',
        'Группа: ________________________________',
        '',
        'Научный руководитель: __________________',
        '',
        '[Город, год]',
      ].join('\n'),
    },
    {
      id: 'contents',
      title: 'Содержание',
      content: contents.map((item, index) => `${index + 1}. ${item}`).join('\n'),
    },
    {
      id: 'introduction',
      title: 'Введение',
      content: [
        `Актуальность темы «${topic}» обусловлена необходимостью углублённого изучения проблемы в контексте современного ${subjectLabel.toLowerCase()}.`,
        'Несмотря на значительное количество исследований, сохраняется потребность в систематизации знаний и разработке практических рекомендаций.',
        requirements ? `Особые требования: ${requirements}` : '',
        '',
        `Цель ${typeLabel.toLowerCase()} — исследовать и раскрыть содержание темы «${topic}».`,
        '',
        'Задачи исследования:',
        ...tasks.map((task, index) => `${index + 1}. ${task}`),
        '',
        `Объект исследования — ${object}.`,
        `Предмет исследования — ${researchSubject}.`,
        '',
        'Методы исследования: анализ научной литературы, сопоставление, обобщение, систематизация материала.',
        'Структура работы: введение, три главы, заключение, список литературы.',
      ].filter(Boolean).join('\n'),
    },
    {
      id: 'mainPart',
      title: 'Основная часть',
      content: chapters.join('\n'),
    },
    {
      id: 'conclusion',
      title: 'Заключение',
      content: [
        `В ходе выполнения ${typeLabel.toLowerCase()} по теме «${topic}» были решены поставленные задачи.`,
        'Теоретический анализ позволил уточнить понятийный аппарат и выявить ключевые подходы к проблеме.',
        'Практическая часть подтвердила значимость выбранного направления исследования.',
        '',
        'Перспективы дальнейшего изучения: углубление эмпирической базы, расширение диагностического материала, апробация рекомендаций в образовательной практике.',
      ].join('\n'),
    },
    {
      id: 'bibliography',
      title: 'Список литературы',
      content: generateBibliographyPlaceholder(subject).join('\n'),
    },
  ];

  return {
    topic,
    subject,
    subjectLabel,
    type,
    typeLabel,
    requirements,
    sections,
    generatedAt: Date.now(),
  };
}

export function buildDocumentText(data) {
  if (!data?.sections?.length) return '';
  return data.sections.map((section) => {
    const title = section.title?.toUpperCase() || '';
    return `${title}\n${'─'.repeat(Math.min(title.length, 48))}\n\n${section.content || ''}`.trim();
  }).join('\n\n\n');
}

export function saveCoursework(data) {
  setItem('coursework_draft', data);
}

export function loadCoursework() {
  return getItem('coursework_draft', null);
}

export function generateBibliographyPlaceholder(subject = 'russian') {
  const base = [
    '1. [Автор, И. О. Название учебника / пособия. — Город: Издательство, год. — XXX с.]',
    '2. [Автор, И. О. Название монографии или статьи // Название журнала. — Год. — № X. — С. XX–XX.]',
    '3. [Название нормативного документа или стандарта. — URL (дата обращения: ДД.ММ.ГГГГ).]',
  ];
  if (subject === 'literature') {
    base.push('4. [Автор произведения. Название произведения / собрание сочинений. — Город: Издательство, год.]');
  }
  if (subject === 'pedagogy') {
    base.push('4. [Автор, И. О. Методическое пособие для педагогов. — Город: Издательство, год.]');
  }
  return base;
}
