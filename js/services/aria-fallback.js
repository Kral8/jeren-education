function extractQuestionCount(message) {
  const match = message.match(/(\d+)\s*вопрос/i);
  if (match) return Math.min(10, Math.max(1, parseInt(match[1], 10)));
  return 3;
}

function detectSubject(message) {
  const lower = message.toLowerCase();
  if (/литератур/.test(lower)) return 'literature';
  if (/русск/.test(lower)) return 'russian';
  return 'mixed';
}

function pickItems(pool, count, offset = 0) {
  const items = [];
  for (let i = 0; i < count; i += 1) {
    items.push(pool[(offset + i) % pool.length]);
  }
  return items;
}

function formatTestReply(message) {
  const count = extractQuestionCount(message);
  const subject = detectSubject(message);
  const russianItems = pickItems(TEST_TEMPLATES.russian, count);
  const literatureItems = pickItems(TEST_TEMPLATES.literature, count);
  const items = subject === 'literature'
    ? literatureItems
    : subject === 'russian'
      ? russianItems
      : [...russianItems.slice(0, Math.ceil(count / 2)), ...literatureItems.slice(0, Math.floor(count / 2))].slice(0, count);

  const title = subject === 'literature'
    ? 'Тест по литературе'
    : subject === 'russian'
      ? 'Тест по русскому языку'
      : 'Тест по русскому языку и литературе';

  let body = `Готово! Ниже — **${title}** для школьников (${count} вопроса).\n\n`;
  items.forEach((item, index) => {
    const letter = ['а', 'б', 'в', 'г'][item.correct];
    body += `### Вопрос ${index + 1}\n${item.q}\n\n`;
    item.options.forEach((opt, i) => {
      body += `${['а', 'б', 'в', 'г'][i]}) ${opt}\n`;
    });
    body += `\n**Ответ:** ${letter}) ${item.options[item.correct]}\n`;
    body += `**Пояснение:** ${item.explain}\n\n---\n\n`;
  });
  body += '_Материал подготовлен в резервном режиме. При необходимости уточните класс или тему — дополню тест._';
  return body;
}

